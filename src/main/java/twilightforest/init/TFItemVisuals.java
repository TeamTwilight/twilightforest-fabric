    public static ItemStack withModel(ItemStack stack, int customModelData) {
        stack.set(DataComponents.CUSTOM_MODEL_DATA, new CustomModelData(customModelData));
        return stack;
    }

    public static int bighornDisplay(DyeColor color, boolean sheared) {
        if (sheared) {
            return BIGHORN_SHEARED_DISPLAY;
        }
        return switch (color) {
            case ORANGE -> BIGHORN_ORANGE_DISPLAY;
            case MAGENTA -> BIGHORN_MAGENTA_DISPLAY;
            case LIGHT_BLUE -> BIGHORN_LIGHT_BLUE_DISPLAY;
            case YELLOW -> BIGHORN_YELLOW_DISPLAY;
            case LIME -> BIGHORN_LIME_DISPLAY;
            case PINK -> BIGHORN_PINK_DISPLAY;
            case GRAY -> BIGHORN_GRAY_DISPLAY;
            case LIGHT_GRAY -> BIGHORN_LIGHT_GRAY_DISPLAY;
            case CYAN -> BIGHORN_CYAN_DISPLAY;
            case PURPLE -> BIGHORN_PURPLE_DISPLAY;
            case BLUE -> BIGHORN_BLUE_DISPLAY;
            case BROWN -> BIGHORN_BROWN_DISPLAY;
            case GREEN -> BIGHORN_GREEN_DISPLAY;
            case RED -> BIGHORN_RED_DISPLAY;
            case BLACK -> BIGHORN_BLACK_DISPLAY;
            default -> BIGHORN_DISPLAY;
        };
    }

    public static int questRamDisplay(int colorFlags) {
        int count = Math.max(0, Math.min(16, Integer.bitCount(colorFlags)));
        return QUEST_RAM_PROGRESS_0_DISPLAY + count;
    }

